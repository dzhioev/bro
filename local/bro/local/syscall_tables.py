#!/usr/bin/env python
import hashlib
import re
import sys
import urllib.request
from pathlib import Path

from bro.base.args import Parser
from bro.files.confinement.classification import CLASSIFICATION, validate_tables

__cli_name__ = 'syscall-tables'

KERNEL_TAG = 'v6.18'
SOURCE_PATHS = {
  'x86_64': 'arch/x86/entry/syscalls/syscall_64.tbl',
  'aarch64': 'include/uapi/asm-generic/unistd.h',
}
OUTPUT = Path(__file__).resolve().parents[3] / 'bro/files/confinement/tables.py'


def x86_table(source: str) -> dict[str, int]:
  table = {}
  for line in source.splitlines():
    fields = line.split()
    if fields and fields[0].isdigit():
      if fields[1] not in ('common', '64', 'x32'):
        raise ValueError(f'unreviewed syscall ABI: {fields[1]}')
      if fields[1] != 'x32':
        table[fields[2]] = int(fields[0])
  return table


def arm_table(source: str) -> dict[str, int]:
  # arm64's native ABI selects renameat, rlimit and memfd_secret, and uses NEW_STAT.
  defined = {
    '__ARCH_WANT_RENAMEAT',
    '__ARCH_WANT_SET_GET_RLIMIT',
    '__ARCH_WANT_MEMFD_SECRET',
    '__ARCH_WANT_NEW_STAT',
  }
  conditions = {
    '__BITS_PER_LONG == 32 || defined(__SYSCALL_COMPAT)': False,
    'defined(__ARCH_WANT_TIME32_SYSCALLS) || __BITS_PER_LONG != 32': True,
    'defined(__ARCH_WANT_NEW_STAT) || defined(__ARCH_WANT_STAT64)': True,
    'defined(__SYSCALL_COMPAT) || __BITS_PER_LONG == 32': False,
    '__BITS_PER_LONG == 64 && !defined(__SYSCALL_COMPAT)': True,
  }
  active = [True]
  numbers: dict[str, int] = {}
  for line in source.splitlines():
    if line.startswith('#ifdef '):
      active.append(active[-1] and line.split()[1] in defined)
    elif line.startswith('#ifndef '):
      active.append(active[-1] and line.split()[1] not in defined)
    elif line.startswith('#if '):
      expression = line.removeprefix('#if ')
      if expression not in conditions:
        raise ValueError(f'unreviewed preprocessor condition: {expression}')
      active.append(active[-1] and conditions[expression])
    elif line.startswith('#elif'):
      raise ValueError(f'unreviewed preprocessor condition: {line}')
    elif line.startswith('#else'):
      active[-1] = active[-2] and not active[-1]
    elif line.startswith('#endif'):
      active.pop()
    elif active[-1] and (match := re.fullmatch(r'#define\s+(__NR\w+)\s+(\w+)\s*', line)):
      name, value = match.groups()
      numbers[name] = int(value) if value.isdigit() else numbers[value]
      defined.add(name)
    elif active[-1] and line.startswith('#define __NR'):
      raise ValueError(f'unreviewed syscall definition: {line}')
    elif line.startswith('#include ') and line != '#include <asm/bitsperlong.h>':
      raise ValueError(f'unreviewed syscall include: {line}')
  if len(active) != 1:
    raise ValueError('unclosed preprocessor condition')
  return {
    name.removeprefix('__NR_'): number
    for name, number in numbers.items()
    if name.startswith('__NR_') and name not in ('__NR_arch_specific_syscall', '__NR_syscalls')
  }


def render(sources: dict[str, bytes]) -> str:
  tables = {
    'x86_64': x86_table(sources['x86_64'].decode()),
    'aarch64': arm_table(sources['aarch64'].decode()),
  }
  validate_tables(tables)
  if set().union(*(set(table) for table in tables.values())) != set(CLASSIFICATION):
    raise ValueError('classification has names outside the pinned tables')
  lines = [
    '# generated by `syscall-tables`; do not edit.',
    f'KERNEL_TAG = {KERNEL_TAG!r}',
    'SOURCE_SHA256 = {',
    *(f'  {arch!r}: {hashlib.sha256(data).hexdigest()!r},' for arch, data in sources.items()),
    '}',
    'TABLES = {',
  ]
  for arch, table in tables.items():
    lines.append(f'  {arch!r}: {{')
    lines.extend(
      f'    {name!r}: {number},' for name, number in sorted(table.items(), key=lambda item: item[1])
    )
    lines.append('  },')
  return '\n'.join([*lines, '}', ''])


def main(argv: list[str]) -> None:
  parser = Parser(description='generate reviewed Linux syscall tables from the pinned kernel tag')
  parser.add_argument(
    '--check', action='store_true', help='fetch, regenerate and compare without writing'
  )
  args = parser.parse(argv)
  sources = {}
  for arch, path in SOURCE_PATHS.items():
    url = f'https://raw.githubusercontent.com/torvalds/linux/{KERNEL_TAG}/{path}'
    with urllib.request.urlopen(url, timeout=60) as response:
      sources[arch] = response.read()
  generated = render(sources)
  if args['check']:
    if OUTPUT.read_text() != generated:
      raise SystemExit('syscall tables differ; regenerate and review the classification')
  else:
    OUTPUT.write_text(generated)


if __name__ == '__main__':
  main(sys.argv)
