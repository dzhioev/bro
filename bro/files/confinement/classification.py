def validate_tables(tables: Mapping[str, Mapping[str, int]]) -> None:
  for name, decision in CLASSIFICATION.items():
    if decision not in ('allowed', 'denied'):
      raise ValueError(f'invalid syscall classification: {name}: {decision}')
  denied = {name for name, decision in CLASSIFICATION.items() if decision == 'denied'}
  for arch, table in tables.items():
    unclassified = set(table) - CLASSIFICATION.keys()
    if unclassified:
      raise ValueError(f'unclassified syscalls on {arch}: {sorted(unclassified)}')
    if len(set(table.values())) != len(table):
      raise ValueError(f'duplicate syscall numbers on {arch}')
    if any(type(number) is not int or number < 0 for number in table.values()):
      raise ValueError(f'invalid syscall numbers on {arch}')
    if denied - table.keys() != ABSENT[arch]:
      raise ValueError(f'denied syscall absent list disagrees on {arch}')
